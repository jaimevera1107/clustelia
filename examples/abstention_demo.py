"""Demonstration of the decision Clustelia makes before clustering.

Four datasets are passed through the same default search:

1. pure noise: one Gaussian cloud, no groups;
2. three separated blobs;
3. one lognormal cloud, no groups, with the default null reference;
4. the same lognormal cloud with the Gaussian-copula reference.

Cases 1 and 2 show the two sides of the decision. Cases 3 and 4 show a
known failure mode of the default reference and the experimental option
that addresses it (``docs/VALIDATION.md``).

Run it as a script to print the report; ``--markdown`` writes the
document used in ``docs/ABSTENTION_DEMO.md``::

    python examples/abstention_demo.py
    python examples/abstention_demo.py --markdown > docs/ABSTENTION_DEMO.md
"""

from __future__ import annotations

import argparse
import sys
import time
import warnings
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any

import numpy as np
from sklearn.datasets import make_blobs

from clustelia import SelectionPolicy, __version__, cluster

SEED: int = 0
N_ROWS: int = 300
N_FEATURES: int = 4


@dataclass(frozen=True)
class Case:
    """One dataset plus the policy used on it."""

    name: str
    question: str
    expect_abstention: bool
    note: str
    data: np.ndarray
    policy: SelectionPolicy | None = None


def build_cases() -> list[Case]:
    """The four datasets of the demonstration, all from ``SEED``."""
    rng = np.random.default_rng(SEED)
    noise = rng.normal(size=(N_ROWS, N_FEATURES))
    blobs, _ = make_blobs(n_samples=N_ROWS, n_features=N_FEATURES,
                          centers=3, cluster_std=0.6, random_state=SEED)
    skewed = np.exp(rng.normal(size=(N_ROWS, 3)))
    return [
        Case("Pure noise", "Are there groups in one Gaussian cloud?",
             True, "no groups exist, so abstention is correct", noise),
        Case("Three separated blobs", "Are there groups when there are?",
             False, "three groups exist and are recovered", blobs),
        Case("Skewed cloud, default reference",
             "Is a skewed single mode mistaken for groups?",
             False, "KNOWN FAILURE: no groups exist, yet the uniform-box "
             "reference is beaten by the skew", skewed),
        Case("Skewed cloud, copula reference",
             "Does the experimental reference fix it?",
             True, "same data, marginal-preserving reference, no groups "
             "reported", skewed,
             SelectionPolicy(null_family="gaussian_copula")),
    ]


def run(case: Case) -> dict[str, Any]:
    """Run the default search on one case and collect what it decided."""
    started = time.perf_counter()
    kwargs: dict[str, Any] = {"random_state": SEED}
    if case.policy is not None:
        kwargs["selection"] = case.policy
    result = cluster(case.data, **kwargs)
    seconds = time.perf_counter() - started
    structure = result.metadata.get("structure_test") or {}
    return {
        "case": case,
        "status": result.selection_status,
        "null_family": result.metadata.get("null_family"),
        "structure_passed": structure.get("passed"),
        "selected_k": result.metadata.get("selected_k"),
        "clusters": result.summary()["n_clusters"],
        "fits": result.metadata["fits_used"],
        "seconds": seconds,
    }


def _flag(outcome: dict[str, Any]) -> str:
    """Whether the run reproduced the behaviour the case documents.

    Case 3 documents a failure, so reproducing it is the expected result;
    "UNEXPECTED" means the run no longer matches the documentation and
    the text below it needs revisiting.
    """
    abstained = outcome["status"] != "recommended"
    matches = abstained == outcome["case"].expect_abstention
    return "as documented" if matches else "UNEXPECTED"


def print_report(outcomes: Sequence[dict[str, Any]]) -> None:
    """Print the plain-text report."""
    for outcome in outcomes:
        case = outcome["case"]
        print(f"\n{case.name}")
        print(f"  question        {case.question}")
        print(f"  null reference  {outcome['null_family']}")
        print(f"  structure test  "
              f"{'passed' if outcome['structure_passed'] else 'failed'}")
        print(f"  decision        {outcome['status']} "
              f"(clusters: {outcome['clusters']}) [{_flag(outcome)}]")
        print(f"  reading         {case.note}")
        print(f"  cost            {outcome['fits']} fits, "
              f"{outcome['seconds']:.1f} s")


def print_markdown(outcomes: Sequence[dict[str, Any]]) -> None:
    """Print the document stored as ``docs/ABSTENTION_DEMO.md``."""
    print("# Does Clustelia actually abstain?\n")
    print("Generated by `python examples/abstention_demo.py --markdown` "
          f"with clustelia {__version__}, seed {SEED}, default `cluster()` "
          "settings. Re-run it to reproduce every number below.\n")
    print("A clustering library that can only ever return clusters is easy "
          "to write. The claim worth checking is the opposite one: that "
          "this search says *no* when the data has no groups, and still "
          "says *yes* when it does.\n")
    print("| Dataset | Null reference | Structure test | Decision | "
          "Clusters | Fits | Time |")
    print("|:--|:--|:--|:--|--:|--:|--:|")
    for outcome in outcomes:
        passed = "passed" if outcome["structure_passed"] else "**failed**"
        clusters = "—" if outcome["clusters"] is None else outcome["clusters"]
        print(f"| {outcome['case'].name} | {outcome['null_family']} | "
              f"{passed} | `{outcome['status']}` | {clusters} | "
              f"{outcome['fits']} | {outcome['seconds']:.1f} s |")
    print("\n## What each row shows\n")
    for outcome in outcomes:
        print(f"- **{outcome['case'].name}.** {outcome['case'].question} "
              f"Decision: `{outcome['status']}` — {outcome['case'].note} "
              f"({_flag(outcome)}).")
    print()
    print("""
Rows 1 and 2 are the two sides of the decision: the same search, the same
settings, opposite answers. Row 1 costs far fewer fits than row 2 because
a failed structure test ends the search before any confirmation fit is
spent.

Rows 3 and 4 are the honest part, and row 3 is a failure reproduced on
purpose. A single lognormal cloud has no groups, but it is skewed, and
the default uniform-box reference reads that skew as structure often
enough to matter: across 30 seeds it recommended a partition in 17 to 20
of 30 such datasets. The experimental
`gaussian_copula` reference preserves every marginal and the rank
correlation, and recommended in 0 to 1 of 30, while still detecting 29 to
30 of 30 real three-group mixtures. One seed is an illustration, not
evidence; the 600-search study behind those rates, with Wilson intervals
and the decision to keep `pca_uniform` as the default, is in
[VALIDATION.md](VALIDATION.md).

## Reading this honestly

The structure test is a screening rule, not a proof. It compares your
data with references built from your own data, so its nominal resolution
(`1 / (null_replicates + 1)`) is not a calibrated false-positive rate.
What these four rows do show is that the decision is real: the same
pipeline reaches opposite verdicts on data that differs only in whether
groups exist.
""".strip())


def main(argv: Sequence[str] | None = None) -> int:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--markdown", action="store_true",
                        help="print the Markdown document instead")
    args = parser.parse_args(argv)
    warnings.filterwarnings("ignore")
    outcomes = [run(case) for case in build_cases()]
    if args.markdown:
        print_markdown(outcomes)
    else:
        print_report(outcomes)
    return 0


if __name__ == "__main__":
    sys.exit(main())
